/**
 * Copies MapLibre's web worker module (and the shared chunk it imports)
 * from node_modules into public/maplibre/ so the browser can load it from
 * a plain same-origin URL.
 *
 * Why this exists: MapLibre GL 6 spawns its worker with
 * `new URL("./maplibre-gl-worker.mjs", import.meta.url)`. Under Next.js
 * with Turbopack, `import.meta.url` inside the bundled chunk is not an
 * http(s) URL, so MapLibre falls back to an empty worker URL, the browser
 * loads the page itself as the worker script, and the worker never
 * answers. Raster tiles still draw (they load on the main thread), but
 * every GeoJSON source stays in "loading" forever, so the route line
 * never appears. components/RouteMap.tsx points MapLibre at the copy made
 * here via maplibregl.setWorkerUrl().
 *
 * Runs on postinstall, predev and prebuild (see package.json), so the copy
 * always matches the installed maplibre-gl version. public/maplibre/ is
 * gitignored; nothing generated is committed.
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = dirname(dirname(fileURLToPath(import.meta.url)));
const distDir = join(appDir, "node_modules", "maplibre-gl", "dist");
const outDir = join(appDir, "public", "maplibre");

const FILES = ["maplibre-gl-worker.mjs", "maplibre-gl-shared.mjs"];

if (!existsSync(distDir)) {
  console.error(
    `[copy-maplibre-worker] ${distDir} not found, is maplibre-gl installed?`,
  );
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
for (const file of FILES) {
  copyFileSync(join(distDir, file), join(outDir, file));
}

const { version } = JSON.parse(
  readFileSync(
    join(appDir, "node_modules", "maplibre-gl", "package.json"),
    "utf8",
  ),
);
writeFileSync(
  join(outDir, "README.txt"),
  `Generated by scripts/copy-maplibre-worker.mjs from maplibre-gl ${version}.\nDo not edit or commit; re-run \`npm run copy:maplibre-worker\` to refresh.\n`,
);
console.log(
  `[copy-maplibre-worker] copied ${FILES.join(", ")} (maplibre-gl ${version}) to public/maplibre/`,
);
